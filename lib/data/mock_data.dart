  /// Builds a single-select multiple_choice question with one correct option.
  static Question _mcq(String id, String title, List<String> options, int correctIndex) {
    const letters = ['a', 'b', 'c', 'd', 'e'];
    return Question(
      id: id,
      type: 'multiple_choice',
      points: 1,
      title: title,
      options: List.generate(
        options.length,
        (i) => QuestionOption(id: letters[i], text: options[i], isCorrect: i == correctIndex),
      ),
    );
  }

